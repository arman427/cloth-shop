/**
 * Honeypot ("горшочек с мёдом"): ловушка для ботов.
 *
 * В форму добавлено поле, которое человек не видит (оно спрятано стилями). Бот, который заполняет
 * все поля подряд, впишет в него текст. Сервер видит заполненное поле и понимает: это бот.
 * Поле выглядит как обычное ("website"), чтобы бот не догадался его пропустить.
 *
 * Бота мы не ругаем: делаем вид, что всё прошло хорошо, ничего не сохраняя. Тогда он не поймёт,
 * что его раскрыли, и не станет искать обход.
 */

/** Имя поля-ловушки. Должно совпадать в форме (components/ui/Honeypot.tsx) и на сервере. */
export const HONEYPOT_FIELD = "website";

/** true, если форму заполнил бот */
export function isBot(formData: FormData): boolean {
   return String(formData.get(HONEYPOT_FIELD) ?? "").trim() !== "";
}
